/**
 * ตำแหน่งของคำสั่งหนึ่งตัวใน AST เช่น
 *   []                       = รายการคำสั่งชั้นบนสุดของ turn()
 *   [{ i: 0, br: 'body' }]   = ข้างใน if ตัวแรก
 *
 * ใช้ index ไม่ใช่ id เพราะ AST ของเราไม่มี id — และ index อ่านง่ายตอนดีบัก
 * ทุกครั้งที่แก้ AST ต้องสร้าง path ใหม่ ห้ามเก็บ path ข้ามการแก้
 */
export interface PathStep {
  /** ลำดับของคำสั่งในรายการนั้น */
  i: number;
  /** กิ่งที่ลงไปต่อ — if มี body/orelse, for มี body */
  br: 'body' | 'orelse';
}

export type StmtPath = PathStep[];

/** ตำแหน่งที่จะ "หย่อน" คำสั่งลงไป: รายการไหน ลำดับที่เท่าไร */
export interface DropSlot {
  parent: StmtPath;
  index: number;
}

export const samePath = (a: StmtPath, b: StmtPath): boolean =>
  a.length === b.length && a.every((s, k) => s.i === b[k].i && s.br === b[k].br);

