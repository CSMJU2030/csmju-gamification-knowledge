/**
 * รวมข้อผิดพลาดซ้ำด้วยคู่ (name + line)
 *
 * ทำไม: validate เดินทั้ง AST จึงรายงานปัญหาเดียวกันได้หลายครั้งในบรรทัดเดียว
 * เช่น `cast("x", a) + cast("x", b)` บรรทัดเดียวได้ ValueError 2 อัน
 * ผู้เล่นใหม่เห็นข้อผิดพลาด 6 บรรทัดจากความผิดพลาดเดียวแล้วเลิกเล่น
 *
 * เก็บข้อความ "แรก" ไว้ (ซ้ายสุดของบรรทัด = ใกล้ต้นเหตุที่สุด) และนับจำนวนที่ซ้ำ
 */
export interface GroupedError {
  name: string;
  line: number;
  col: number;
  messageTh: string;
  /** จำนวนครั้งที่เจอปัญหาชื่อเดียวกันในบรรทัดเดียวกัน */
  count: number;
}

export function groupErrors(
  errors: { name: string; line: number; col: number; messageTh: string }[],
): GroupedError[] {
  const byKey = new Map<string, GroupedError>();
  for (const e of errors) {
    const key = `${e.name}@${e.line}`;
    const seen = byKey.get(key);
    if (seen) {
      seen.count += 1;
      if (e.col < seen.col) {
        seen.col = e.col;
        seen.messageTh = e.messageTh;
      }
      continue;
    }
    byKey.set(key, { name: e.name, line: e.line, col: e.col, messageTh: e.messageTh, count: 1 });
  }
  return [...byKey.values()].sort((a, b) => a.line - b.line || a.col - b.col);
}

